const ISLANDS: readonly IslandId[] = ['A', 'B', 'C'];

/**
 * Islands are the three AZs of the city. Placement is cosmetic: each district's
 * buildings are spread across A, B and C in order so every district looks multi-AZ.
 */
export function withIslands(defs: readonly BuildingDef[]): Building[] {
  const counters = new Map<string, number>();
  return defs.map((def) => {
    if (def.district === 'square') return { ...def, island: null };
    const n = counters.get(def.district) ?? 0;
    counters.set(def.district, n + 1);
    return { ...def, island: ISLANDS[n % ISLANDS.length] ?? 'A' };
  });
}

export const BUILDINGS: readonly Building[] = withIslands(BUILDING_DEFS);

/** npx tsx scripts/puzzle-report.ts > docs/step-5-puzzle-facts.md: counts, rules with sources, and one worked sample per type. */
import { BUILDINGS } from '../src/data/buildings.ts';
import { DISTRICT_BY_ID } from '../src/data/districts.ts';
import { PUZZLE_TYPE_NAME, PUZZLE_TYPES } from '../src/puzzles/types.ts';
import { loadPuzzles } from './lib/loadPuzzles.ts';
import { loadNotesBundle } from './lib/loadNotes.ts';
import { scenarioText } from './lib/puzzleChecks.ts';

const modules = await loadPuzzles();
const { sources } = await loadNotesBundle();
const url = new Map(sources.map((s) => [s.id, s.url]));
const bld = new Map(BUILDINGS.map((b) => [b.id, b]));
const domainName = (id: string) => {
  const d = DISTRICT_BY_ID[bld.get(id)?.district as keyof typeof DISTRICT_BY_ID];
  return d?.domain ? `Domain ${d.domain}` : 'Foundation (no domain)';
};
const out: string[] = ['# Step 5 puzzle facts (generated by `scripts/puzzle-report.ts`)', ''];

out.push('## Counts', '', '| Type | Scenarios | Buildings | Domains |', '| --- | --- | --- | --- |');
const perBuilding: string[] = [];
let total = 0;
for (const t of PUZZLE_TYPES) {
  const m = modules.get(t);
  if (!m) continue;
  total += m.scenarios.length;
  const byB = new Map<string, number>();
  const byD = new Map<string, number>();
  for (const s of m.scenarios) {
    byB.set(s.building, (byB.get(s.building) ?? 0) + 1);
    byD.set(domainName(s.building), (byD.get(domainName(s.building)) ?? 0) + 1);
  }
  out.push(`| ${PUZZLE_TYPE_NAME[t]} | ${m.scenarios.length} | ${[...byB].map(([b, n]) => `${b} ${n}`).join(', ')} | ${[...byD].map(([d, n]) => `${d}: ${n}`).join(', ')} |`);
  for (const [b, n] of byB) perBuilding.push(`${b} (${domainName(b)}): ${PUZZLE_TYPE_NAME[t]} ${n}`);
}
out.push('', `Total: ${total} scenarios.`, '', '## By building', '', ...perBuilding.map((x) => `- ${x}`), '');

out.push('## Rules and their AWS sources', '');
for (const t of PUZZLE_TYPES) {
  const m = modules.get(t);
  if (!m) continue;
  out.push(`### ${PUZZLE_TYPE_NAME[t]}`, '');
  if (m.def.rules.length === 0) out.push('Authored facts per scenario (each set carries four sourced facts); see the scenario file.', '');
  else {
    out.push('| Rule | What it says | Source |', '| --- | --- | --- |');
    for (const r of m.def.rules) out.push(`| ${r.id} | ${r.text.replaceAll('|', '/')} | ${url.get(r.src) ?? r.src} |`);
    out.push('');
  }
}

out.push('## One sample per type', '');
for (const t of PUZZLE_TYPES) {
  const m = modules.get(t);
  if (!m) continue;
  const s = m.scenarios[Math.min(2, m.scenarios.length - 1)] as (typeof m.scenarios)[number];
  const ev = m.def.evaluate(s.data);
  out.push(`### ${PUZZLE_TYPE_NAME[t]}: ${s.id} (${s.title}, level ${s.difficulty}, ${s.building})`, '', s.story, '');
  for (const sec of m.def.exhibit(s.data)) out.push(sec.kind === 'table' ? `**${sec.title}**\n\n${[sec.head, ...sec.rows].map((r, i) => `| ${r.join(' | ')} |${i === 0 ? `\n|${sec.head.map(() => ' --- |').join('')}` : ''}`).join('\n')}\n` : `**${sec.title}**\n\n\`\`\`\n${sec.text}\n\`\`\`\n`);
  for (const f of m.def.fields(s.data)) out.push(`- ${f.prompt}\n  - Computed answer: ${(ev?.answer[f.id] ?? []).map((id) => f.options.find((o) => o.id === id)?.label ?? id).join(' | ')}`);
  out.push('', '**Why:**', ...(ev?.trace ?? []).map((x) => `- ${x.note}`), '');
  void scenarioText;
}
console.log(out.join('\n'));

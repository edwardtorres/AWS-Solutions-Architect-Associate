import { planOf } from '../../content/labs/services.ts';
import { labOrder, type Lab, type LabMeta } from '../../src/labs/types.ts';

export function labMetaOf(lab: Lab): LabMeta {
  return {
    id: lab.id,
    n: lab.n,
    title: lab.title,
    goal: lab.goal,
    minutes: lab.minutes,
    buildings: lab.buildings,
    bullets: lab.bullets,
    needs: lab.needs,
    services: lab.services,
    plan: planOf(lab.services),
    last: lab.last === true,
    newer: [...new Set([...(lab.newer ?? []), ...lab.steps.flatMap((s) => s.newer ?? [])])].sort(),
    gated: lab.gate !== undefined,
    billable: lab.costs.map((c) => c.resource),
    steps: lab.steps.length,
    required: lab.steps.filter((s) => s.kind === 'cleanup' || s.kind === 'verify').map((s) => s.id),
    templates: (lab.templates ?? []).length,
  };
}

/** Source of src/labs/meta.ts. */
export function buildLabMetaSource(labs: readonly Lab[]): string {
  const rows = labOrder(labs).map((l) => `  ${JSON.stringify(labMetaOf(l))},`);
  return `// Generated by scripts/gen-question-meta.ts. Do not edit. Run \`npm run gen:meta\`.
// What the Labs page, the Workshop section and the engine need without loading the lab text.
import type { LabMeta } from './types';

export const LAB_META: readonly LabMeta[] = [
${rows.join('\n')}
];

export const LAB_META_BY_ID: ReadonlyMap<string, LabMeta> = new Map(LAB_META.map((l) => [l.id, l]));
`;
}

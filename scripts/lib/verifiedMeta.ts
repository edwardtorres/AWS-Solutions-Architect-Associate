import { oldestDate, type Citers } from './citations.ts';
import type { HashFile } from './freshness.ts';

/**
 * The building -> "last checked on AWS docs" date: the oldest verifiedAt among every page the building's notes, questions,
 * puzzles and labs cite. A building that cites a page with no stored date has no date (it shows "not yet checked").
 */
export function buildingDates(hashes: HashFile, citations: ReadonlyMap<string, Citers>, buildingIds: readonly string[], sourceUrl: ReadonlyMap<string, string>): Record<string, string> {
  const dateOfSource = (src: string): string | undefined => {
    const url = sourceUrl.get(src);
    return url ? hashes.pages[url]?.verifiedAt : undefined;
  };
  const out: Record<string, string> = {};
  for (const id of buildingIds) {
    const dates: (string | undefined)[] = [];
    for (const [src, c] of citations) if (c.buildings.has(id)) dates.push(dateOfSource(src));
    const d = oldestDate(dates);
    if (d) out[id] = d;
  }
  return out;
}

export function buildVerifiedSource(dates: Record<string, string>, generated: string): string {
  const rows = Object.entries(dates).sort(([a], [b]) => a.localeCompare(b)).map(([id, d]) => `  '${id}': '${d}',`);
  return `// Generated by scripts/gen-question-meta.ts (npm run gen:meta) from content/page-hashes.json. Do not edit.\n/** Building id to the oldest date on which any page it cites was last checked against AWS documentation. */\nexport const BUILDING_VERIFIED: Record<string, string> = {\n${rows.join('\n')}\n};\n\nexport const HASHES_GENERATED = '${generated}';\n`;
}

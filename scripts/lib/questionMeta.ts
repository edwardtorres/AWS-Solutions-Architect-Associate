import type { Question } from '../../src/content/types.ts';

/** Source of src/questions/meta.ts: id, building, bullets and difficulty only (no stems, options or tags). */
export function buildMetaSource(questions: readonly Question[]): string {
  const rows = [...questions]
    .sort((a, b) => (a.id < b.id ? -1 : 1))
    .map((q) => `  ${JSON.stringify([q.id, q.building, q.bullets.join(' '), q.difficulty])},`);
  return `// Generated by scripts/gen-question-meta.ts. Do not edit. Run \`npm run gen:meta\`.
// Only what readiness and progress need: no stems, options, keys or tags.
import type { QMeta } from '../game/readiness';

const ROWS: readonly (readonly [string, string, string, 1 | 2 | 3])[] = [
${rows.join('\n')}
];

export const QUESTION_META: ReadonlyMap<string, QMeta> = new Map(
  ROWS.map(([id, building, bullets, difficulty]) => [id, { id, building, bullets: bullets === '' ? [] : bullets.split(' '), difficulty }]),
);
`;
}
